
public class FruitType {
	private String fruit;
	private int anotatoOrio;
	
	public FruitType(String fruit, int anotatoOrio) {
		super();
		this.fruit = fruit;
		this.anotatoOrio = anotatoOrio;
	}

	public String getFruit() {
		return fruit;
	}

	public void setFruit(String fruit) {
		this.fruit = fruit;
	}
	
	
	
}
