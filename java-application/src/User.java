
public class User {
	private String name;
	private String lastname;
	private int phonenumber;
	private int code;
	private int afm;
	
	
	public User(String name, String lastname, int phonenumber, int code, int afm) {
		super();
		this.name = name;
		this.lastname = lastname;
		this.phonenumber = phonenumber;
		this.code = code;
		this.afm = afm;
	}
	
	
	
	
}
